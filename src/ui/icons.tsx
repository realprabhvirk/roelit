type Props = {
  name: string;
  size?: number;
  class?: string;
  style?: JSX.CSSProperties;
  label?: string;
};

export function Icon({ name, size = 22, class: cls, style, label }: Props) {
  const svg = SVGS[name] ?? SVGS.cards;
  return (
    <span
      class={'icon' + (cls ? ' ' + cls : '')}
      style={{ width: size, height: size, ...style }}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
